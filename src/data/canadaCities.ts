export interface CanadaCityExtended extends CanadaCity {
  ascii: string;
  alt: string[];
}

export function normalizeAscii(input: string): string {
  return String(input || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}

export const ALL_CANADA_CITIES: CanadaCityExtended[] = RAW_CANADA_MUNICIPALITIES.map(
  ([name, admin, lat, lon, population, alt]) => ({
    name,
    ascii: normalizeAscii(name),
    country: 'Canada',
    countryIso: 'CA',
    admin,
    lat,
    lon,
    population,
    alt: Array.isArray(alt) ? alt : [],
  })
);

export const CANADA_CITIES_BY_PROVINCE: Record<string, CanadaCityExtended[]> = ALL_CANADA_CITIES.reduce(
  (acc, city) => {
    if (!acc[city.admin]) {
      acc[city.admin] = [];
    }
    acc[city.admin].push(city);
    return acc;
  },
  {} as Record<string, CanadaCityExtended[]>
);

// Ensure every province's cities are sorted by population descending, then alphabetically
Object.keys(CANADA_CITIES_BY_PROVINCE).forEach((code) => {
  CANADA_CITIES_BY_PROVINCE[code].sort(
    (a, b) => (b.population || 0) - (a.population || 0) || a.name.localeCompare(b.name)
  );
});

