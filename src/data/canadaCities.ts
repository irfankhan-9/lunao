export function getLocalCanadaCitiesForProvince(provinceCode: string, limit = 500): CanadaCityExtended[] {
  if (!provinceCode) return [];
  const code = provinceCode.trim().toUpperCase();
  const list = CANADA_CITIES_BY_PROVINCE[code] || [];
  return list.slice(0, Math.max(1, limit));
}

export function filterProvinceCities(cities: CanadaCityExtended[], query: string): CanadaCityExtended[] {
  const q = normalizeAscii(query);
  if (!q) return cities;
  return cities.filter((c) => {
    const nameAscii = c.ascii || normalizeAscii(c.name);
    if (nameAscii.includes(q)) return true;
    if (Array.isArray(c.alt)) {
      return c.alt.some((a) => normalizeAscii(a).includes(q));
    }
    return false;
  });
}
