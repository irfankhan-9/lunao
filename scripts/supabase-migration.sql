-- 1. Tenants & Business Profiles
CREATE TABLE IF NOT EXISTS tenants (
  id TEXT PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  niche TEXT DEFAULT 'Local Business',
  tagline TEXT,
  logo_url TEXT,
  phone TEXT,
  email TEXT,
  address TEXT,
  city TEXT,
  timezone TEXT,
  website_url TEXT,
  social_links JSONB DEFAULT '{}'::jsonb,
  theme JSONB DEFAULT '{"accent": "#059669", "accentDark": "#047857", "accentSoft": "#ecfdf5", "accentBorder": "#a7f3d0"}'::jsonb,
  features JSONB DEFAULT '{"booking": true, "chatbot": true, "email": true, "automations": true}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Bookings Table (Synced from public website forms, widgets, and Owner PWA)
CREATE TABLE IF NOT EXISTS bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL,
  business_name TEXT,
  customer_name TEXT,
  phone TEXT,
  email TEXT,
  service TEXT,
  date TEXT,
  time TEXT,
  notes TEXT,
  source TEXT DEFAULT 'form',
  status TEXT DEFAULT 'new',
  created_at BIGINT,
  created_at_tz TIMESTAMPTZ DEFAULT NOW()
);

-- Index for instant querying by tenant slug
CREATE INDEX IF NOT EXISTS idx_bookings_slug ON bookings(slug);
CREATE INDEX IF NOT EXISTS idx_bookings_created ON bookings(created_at DESC);

-- 3. Chat Sessions & Messages (AI Receptionist & Live Visitor Chat)
CREATE TABLE IF NOT EXISTS chat_sessions (
  id TEXT PRIMARY KEY,
  slug TEXT NOT NULL,
  created_at BIGINT,
  created_at_tz TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id TEXT NOT NULL REFERENCES chat_sessions(id) ON DELETE CASCADE,
  slug TEXT NOT NULL,
  role TEXT NOT NULL,
  content TEXT NOT NULL,
  created_at BIGINT,
  created_at_tz TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_chat_messages_session ON chat_messages(session_id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_slug ON chat_messages(slug);

-- 4. Customers Table
CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL,
  name TEXT NOT NULL,
  phone TEXT,
  email TEXT,
  notes TEXT,
  created_at BIGINT,
  updated_at BIGINT
);

CREATE INDEX IF NOT EXISTS idx_customers_slug ON customers(slug);

-- 5. Automations Table
CREATE TABLE IF NOT EXISTS automations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL,
  key TEXT NOT NULL,
  enabled BOOLEAN DEFAULT true,
  updated_at BIGINT,
  CONSTRAINT uq_automations_slug_key UNIQUE (slug, key)
);

